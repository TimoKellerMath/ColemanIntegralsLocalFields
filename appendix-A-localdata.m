// appendix-A-localdata.m          [Appendix A, steps (ii) and (v): the local data at ONE split prime]
//
//    magma q:=41 appendix-A-localdata.m
//
// writes appendix-A-local-41.dat, a purely combinatorial description of everything the
// Mordell-Weil sieve needs at q = 41.  Splitting the computation this way keeps each
// run short and, more importantly, makes appendix-A-sieve.m independent of the curve: the
// sieve then runs on finite abelian groups only.
//
// The groups.  Gamma = < c_spor > + J(C)(F)_tors = < t_10, z, c_spor > with z = c_spor
// + fam (D_6 is redundant: it has order 3 and lies in < z >, see appendix-A-generators.m),
// and f : Z^3 -> H_q := red_q(Gamma) sends the standard basis to (t_10, z, c_spor).
// Since [J(C)(F) : Gamma] divides 2 but is not known, the sieve may NOT assume that
// red_q(iota_2(D)) lies in H_q for a global divisor D; all that is known is
//     red_q(iota_2(D)) in red_q(J(C)(F)) subset H_q^rob := { y : 2y in H_q } .
// The classes stored below are therefore those of  A_q cap H_q^rob, each of them
// recorded by the f-preimage vector of its DOUBLE (which does lie in H_q, so it has
// one); the sieve uses the multiplier jmath = 2*iota_2 : C^(2)(F) -> Gamma.  For the
// conditional variant "Gamma = J(C)(F)" the preimage vector of the class itself is
// stored as well, whenever the class happens to lie in H_q.
//
// What is stored, per class c of A_q cap H_q^rob:
//   * vec(2c), and the type (a)/(b)/(c), the shape of the underlying divisor (split /
//     diagonal / conjugate), whether that divisor meets the line at infinity, and
//     whether it is a pullback;
//   * whether c itself lies in H_q, and if so vec(c);
// together with generators of Ker(f), so that H_q = Z^3/Ker(f) can be rebuilt
// abstractly, and vec(2c) for each of the known divisors of K_2, in the fixed order of
// KnownNames.
SetColumns(0);
if not assigned q then q := 41; end if;
q := StringToInteger(Sprint(q));
SetLogFile(Sprintf("appendix-A-localdata-%o.log", q) : Overwrite);
load "appendix-A-common.m";

L := LocalData(q);
assert L`ok and L`cspor_ok and L`fam_ok;
H := L`Hp;
Hrob := L`Hrob;
Z3 := FreeAbelianGroup(3);
f  := hom< Z3 -> H | [ H!L`t10, H!L`ztor, H!L`cspor ] >;
K  := Kernel(f);
vec := function(c) return Eltseq((H!c) @@ f); end function;
printf "q = %o : |H_q| = %o, invariants %o, ord(c_spor) = %o, [H_q^rob : H_q] = %o\n",
   q, #H, Invariants(H), Order(L`cspor), #Hrob div #H;

Aq, famcl, crosscl, typ, tag, inf := DegreeTwoData(L);
// A printable description of the effective divisor representing each class (iota_2 is
// injective on C_q^(2)(F_q), so the divisor is determined by the class).  Building it
// costs a second pass of discrete logarithms over all of C_q^(2)(F_q), so it is only
// done on request:   magma q:=41 withdesc:=1 appendix-A-localdata.m
desc := AssociativeArray();
if assigned withdesc then
pl1 := Places(L`Cq,1); pl2 := Places(L`Cq,2);
for i in [1..#pl1] do
  for j in [i..#pl1] do
    c := ((1*pl1[i] + 1*pl1[j]) - L`D0q)@@L`mCl;
    desc[c] := Sprintf("%o + %o", Eltseq(RepresentativePoint(pl1[i])), Eltseq(RepresentativePoint(pl1[j])));
  end for;
end for;
for pl in pl2 do
  c := (1*pl - L`D0q)@@L`mCl;
  desc[c] := Sprintf("conj pair %o", Eltseq(RepresentativePoint(pl)));
end for;
end if;
printf "  #A_q = %o = %o (a) + %o (b) + %o (c)\n", #Aq,
   #[c : c in Aq | typ[c] eq "a"], #[c : c in Aq | typ[c] eq "b"], #[c : c in Aq | typ[c] eq "c"];
// iota_{2,q} must be injective on C_q^(2)(F_q) for a class to determine a residue class
// (gon(C_q) > 2); step (vii) of appendix-A-sieve.m identifies the two, so this is checked.
n1 := #Places(L`Cq, 1); n2 := #Places(L`Cq, 2);
printf "  #C_q^(2)(F_q) = %o*%o/2 + %o = %o : iota_{2,q} injective = %o\n",
   n1, n1+1, n2, (n1*(n1+1)) div 2 + n2, (n1*(n1+1)) div 2 + n2 eq #Aq;
assert (n1*(n1+1)) div 2 + n2 eq #Aq;
AHr := [ c : c in Aq | c in Hrob ];
AH  := [ c : c in AHr | c in H ];
printf "  #(A_q cap H_q)     = %o, of which pullbacks: %o, so #R_q     = %o\n",
   #AH, #[c : c in AH | c in famcl], #[c : c in AH | c notin famcl];
printf "  #(A_q cap H_q^rob) = %o, of which pullbacks: %o, so #R_q^rob = %o\n",
   #AHr, #[c : c in AHr | c in famcl], #[c : c in AHr | c notin famcl];
printf "  type (c) classes in H_q: %o of %o ; in H_q^rob: %o of %o\n",
   #[c : c in crosscl | c in H], #crosscl, #[c : c in crosscl | c in Hrob], #crosscl;
// how much is lost by doubling: 2 is not injective on H_q^rob
printf "  #{ 2c : c in R_q^rob } = %o (the honest local condition for jmath = 2*iota_2)\n",
   #{ 2*c : c in AHr | c notin famcl };

KL := KnownList(L);
printf "  known divisors of K_2 that reduce well here: %o of %o\n",
   #[e : e in KL | e[2]], #KL;

for c in AHr do if not IsDefined(desc, c) then desc[c] := ""; end if; end for;
fh := Open(Sprintf("appendix-A-local-%o.dat", q), "w");
fprintf fh, "// AUTOGENERATED by appendix-A-localdata.m -- do not edit.\n";
fprintf fh, "// H_%o = red_%o(Gamma) = Z^3/Rel with basis (t_10, z, c_spor).\n", q, q;
fprintf fh, "LocalQ   := %o;\n", q;
fprintf fh, "LocalRel := %o;\n", [ Eltseq(Z3!k) : k in Generators(K) ];
// classes of A_q cap H_q^rob:
//   < vec(2c), type, tag, at infinity, pullback, description, c in H_q, vec(c) or 0 >
fprintf fh, "LocalAH  := [\n";
for i in [1..#AHr] do
  c := AHr[i];
  inH := c in H;
  fprintf fh, "  < %o, \"%o\", \"%o\", %o, %o, \"%o\", %o, %o >%o\n", vec(2*c), typ[c], tag[c],
     inf[c] select "true" else "false", (c in famcl) select "true" else "false",
     desc[c], inH select "true" else "false", inH select vec(c) else [0,0,0],
     i lt #AHr select "," else "";
end for;
fprintf fh, "];\n";
// the known divisors, in the order of KnownNames:
//   < vec(2*[D-D_0]), ok, [D-D_0] in H_q, vec([D-D_0]) >
// (the last vector is meaningless unless the third entry is true; note that it is
// [0,0,0] for D = D_0 itself, which is why the flag cannot be inferred from it)
fprintf fh, "LocalKnown := [\n";
for i in [1..#KL] do
  e := KL[i];
  ok  := e[2] and (2*e[1] in H);
  inH := e[2] and (e[1] in H);
  fprintf fh, "  < %o, %o, %o, %o >%o\n", ok select vec(2*e[1]) else [0,0,0],
     ok select "true" else "false", inH select "true" else "false",
     inH select vec(e[1]) else [0,0,0],
     i lt #KL select "," else "";
end for;
fprintf fh, "];\n";
delete fh;
printf "wrote appendix-A-local-%o.dat\n", q;
print "DONE";
printf "\nresources: CPU time %o s, maximum memory %o MB\n", Cputime(), Round(GetMaximumMemoryUsage()/2^20);
exit;

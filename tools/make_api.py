#!/usr/bin/env python3
"""Build the API reference docs/API.md from the comments in the library files.

    python3 tools/make_api.py           # write docs/API.md
    python3 tools/make_api.py --check   # fail if docs/API.md is out of date

Every function of the library begins with a comment stating its input, its output and the
algorithm or result of the article it implements. The reference collects them: for every
library file (in load order) its header comment, then every user-facing function (the
intrinsics of the package, USER_FUNCTIONS in tools/make_package.py) with its signature, the
defaults of its options and its full comment, and finally the other functions of the file
with their signatures and the first sentence of their comments.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_package  # noqa: E402

ROOT = make_package.ROOT
API = ROOT / "docs" / "API.md"
DEFINITION = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s*:=\s*(function|procedure)\s*\(", re.M)


def file_header(text):
    """The comment at the top of a library file, without the comment markers."""
    lines = []
    for line in text.split("\n"):
        if not line.startswith("//"):
            break
        lines.append(line[3:] if line.startswith("// ") else line[2:])
    return "\n".join(lines).strip("\n")


ABBREVIATIONS = ("w.r.t.", "e.g.", "i.e.", "resp.", "cf.", "etc.")


def first_sentence(comment):
    """The first sentence of a comment (its first paragraph up to the first full stop or
    semicolon outside brackets that does not end an abbreviation), a long one only up to its
    first colon outside brackets (which usually introduces the details)."""
    para = " ".join(comment.strip().split("\n\n")[0].split())
    depth, end, colon = 0, len(para), None
    for k, ch in enumerate(para):
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth = max(depth - 1, 0)
        elif depth == 0 and (k + 1 == len(para) or para[k + 1] == " "):
            if ch in ".;" and not any(para[:k + 1].endswith(a) for a in ABBREVIATIONS):
                end = k + 1
                break
            if ch == ":" and colon is None:
                colon = k
    s = para[:end].strip()
    if len(s) > 160 and colon is not None and colon >= 40:
        s = para[:colon] + "."
    return s


def signature(name, positional, options):
    opts = ", ".join(f"{k} := {d}" for k, d in options)
    return f"{name}({', '.join(positional)}{' : ' + opts if opts else ''})"


def anchor(name):
    """The anchor of the heading "### name" on GitHub (lower case; underscores are kept)."""
    return name.lower()


def build():
    sources = {f: (ROOT / f).read_text() for f in make_package.LIBRARY}
    user = set(make_package.USER_FUNCTIONS)
    out = ["# API reference", "",
           "Generated by `tools/make_api.py` from the comments at the beginning of the library files",
           "and functions (do not edit; `make api` rebuilds it, `make check` fails if it is out of",
           "date). The functions are documented as they are called after `load`ing the library",
           "(README.md, \"Getting started\"); the package (`AttachSpec`) provides the user-facing ones",
           "as intrinsics with the same names, arguments and options, and the verbosity flag",
           "`ColemanIntegration` instead of `User1`.", "",
           "## User-facing functions", ""]
    for f in make_package.LIBRARY:
        names = [m.group(1) for m in DEFINITION.finditer(sources[f]) if m.group(1) in user]
        if names:
            out.append(f"* `{f}`: " + ", ".join(f"[`{n}`](#{anchor(n)})" for n in names))
    out.append("")
    for f in make_package.LIBRARY:
        text = sources[f]
        out += [f"## {f}", "", "```text", file_header(text), "```", ""]
        defs = [(m.group(1), m.group(2)) for m in DEFINITION.finditer(text)]
        for name, kind in defs:
            if name not in user:
                continue
            positional, options, help_text = make_package.parse_function(text, name, package=False)
            out += [f"### {name}", "", "```magma", signature(name, positional, options), "```", "",
                    "```text", help_text, "```", ""]
        others = [(n, k) for n, k in defs if n not in user]
        if others:
            out += [f"Other functions of `{f}`:", ""]
            for name, kind in others:
                positional, options, help_text = make_package.parse_function(text, name, package=False)
                desc = first_sentence(help_text) if help_text.strip() else ""
                out.append(f"* `{signature(name, positional, options)}`" + (f" -- {desc}" if desc else "")
                           + (" (procedure)" if kind == "procedure" else ""))
            out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if docs/API.md is not up to date")
    args = ap.parse_args()
    text = build()
    if args.check:
        if not API.exists() or API.read_text() != text:
            print("make_api: docs/API.md is out of date; run `python3 tools/make_api.py`", file=sys.stderr)
            return 1
        print("make_api: docs/API.md is up to date")
        return 0
    API.parent.mkdir(exist_ok=True)
    API.write_text(text)
    n = sum(1 for f in make_package.LIBRARY for _ in DEFINITION.finditer((ROOT / f).read_text()))
    print(f"make_api: wrote {API.relative_to(ROOT)} ({len(make_package.USER_FUNCTIONS)} user-facing functions, {n} in all)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
